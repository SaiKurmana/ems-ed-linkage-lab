"""Run integration patterns A, B and C over the synthetic EMS/ED data.

Writes:
  data/patterns/ed_records_{A,B,C}.parquet   ED records as each pattern leaves them (ems_uuid may be null)
  results/pattern_logs.json                  stage counts, carry rates
  examples/pattern_{a,b,c}/...               human-readable sample messages / bundles

Usage:  python -m patterns.simulate --config config/default.yaml
"""

from __future__ import annotations

import argparse
import json
import shutil
import time

import numpy as np
import pandas as pd

from common import DISCLAIMER
from common.config import load_config, resolve_paths
from common.io import write_json, write_parquet
from patterns import pattern_a, pattern_b, pattern_c

PATTERNS = {"A": pattern_a, "B": pattern_b, "C": pattern_c}
HEADER_HL7 = (
    f"# {DISCLAIMER} Synthetic HL7 v2.5.1 message(s) generated by ems-ed-linkage-lab.\n"
    "# Segments are shown one per line; on the wire they are separated by carriage returns.\n"
)


def load_raw(cfg):
    raw = resolve_paths(cfg)["data_dir"] / "raw"
    return (
        pd.read_parquet(raw / "ems_records.parquet"),
        pd.read_parquet(raw / "ed_encounters.parquet"),
        pd.read_parquet(raw / "truth_links.parquet"),
    )


def write_examples(cfg, results: dict) -> None:
    ex_dir = resolve_paths(cfg)["examples_dir"]
    for key in ("pattern_a", "pattern_b", "pattern_c"):
        shutil.rmtree(ex_dir / key, ignore_errors=True)
        (ex_dir / key).mkdir(parents=True)
    for i, ex in enumerate(results["A"]["examples"], 1):
        (ex_dir / "pattern_a" / f"example_{i}_ems_ADT_A05.hl7").write_text(
            HEADER_HL7 + ex["ems_a05"], encoding="utf-8"
        )
        (ex_dir / "pattern_a" / f"example_{i}_hospital_ADT_A04.hl7").write_text(
            HEADER_HL7 + ex["hospital_a04"], encoding="utf-8"
        )
    for i, ex in enumerate(results["B"]["examples"], 1):
        (ex_dir / "pattern_b" / f"example_{i}_ems_to_hie_ADT_A04.hl7").write_text(
            HEADER_HL7 + ex["ems_a04_to_hie"], encoding="utf-8"
        )
        (ex_dir / "pattern_b" / f"example_{i}_ed_to_hie_ADT_A04.hl7").write_text(
            HEADER_HL7 + ex["ed_a04_to_hie"], encoding="utf-8"
        )
        (ex_dir / "pattern_b" / f"example_{i}_hie_writeback_ADT_A08.hl7").write_text(
            HEADER_HL7 + ex["hie_a08_writeback"], encoding="utf-8"
        )
    for i, ex in enumerate(results["C"]["examples"], 1):
        for name in ("transaction_bundle", "ed_record_bundle"):
            b = dict(ex[name])
            b["meta"] = {
                "tag": [
                    {
                        "system": "https://ems-ed-linkage-lab.example.org/tags",
                        "code": "synthetic",
                        "display": DISCLAIMER,
                    }
                ]
            }
            path = ex_dir / "pattern_c" / f"example_{i}_{name}.json"
            path.write_text(json.dumps(b, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def simulate(cfg: dict, validate_all_fhir: bool = True) -> dict:
    ems, ed, links = load_raw(cfg)
    seed = int(cfg["seed"])
    results, logs = {}, {}
    for i, (k, mod) in enumerate(PATTERNS.items()):
        rng = np.random.default_rng(seed + 101 * (i + 1))
        t0 = time.perf_counter()
        kwargs = {"validate_all": validate_all_fhir} if k == "C" else {}
        res = mod.run(ems, ed, links, cfg, rng, **kwargs)
        res["log"]["runtime_seconds"] = round(time.perf_counter() - t0, 2)
        results[k] = res
        logs[k] = res["log"]
    return {"results": results, "logs": logs}


def save(cfg: dict, sim: dict) -> None:
    paths = resolve_paths(cfg)
    for k, res in sim["results"].items():
        write_parquet(
            res["ed_records"],
            paths["data_dir"] / "patterns" / f"ed_records_{k}.parquet",
            "ed_encounter_id",
        )
    logs = {
        k: {kk: vv for kk, vv in v.items() if kk != "runtime_seconds"}
        for k, v in sim["logs"].items()
    }
    write_json(
        {"disclaimer": DISCLAIMER, "patterns": logs}, paths["results_dir"] / "pattern_logs.json"
    )
    write_json(
        {k: v["runtime_seconds"] for k, v in sim["logs"].items()},
        paths["data_dir"] / "pattern_runtime.json",
    )
    write_examples(cfg, sim["results"])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default=None)
    args = ap.parse_args(argv)
    cfg = load_config(args.config)
    sim = simulate(cfg)
    save(cfg, sim)
    print(f"[patterns] {DISCLAIMER}")
    for k, log in sim["logs"].items():
        print(f"  {k}: " + ", ".join(f"{kk}={vv}" for kk, vv in log.items()))


if __name__ == "__main__":
    main()
